#!/usr/bin/env python3
"""Build hash-verified offline, theme-matched media from a Pose Hub release.

The source release is read-only. The CLI bundles both realistic themes for App
exercise metadata, plus build-time compressed theme keyframes. The original
small-bundle API is retained with --legacy-small-bundle.
Relative release paths are preserved so the same manifests work for assets and
HTTP downloads. No video encoding or manifest rewriting is performed.

Preview: python tools/media/build_on_demand_assets.py --source <v0.3.0-app>
Apply:   python tools/media/build_on_demand_assets.py --source <v0.3.0-app> --apply
Verify:  python tools/media/build_on_demand_assets.py --source <v0.3.0-app> --verify-only
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import tempfile
import zipfile


APP_ROOT = Path(__file__).resolve().parents[2]
BUNDLED_PACKAGES = ("builtin", "realistic-dark")
BUILTIN_VIDEO_COUNT = 32
BEGIN = "    # BEGIN training media (generated by tools/media/build_on_demand_assets.py)"
END = "    # END training media"


class AssetError(ValueError):
    """An input or existing output does not satisfy the release contract."""


@dataclass(frozen=True)
class MediaFile:
    source: Path
    relative: str
    size: int
    sha256: str
    group: str


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def inventory_hash(files: list[MediaFile]) -> str:
    values = [f"{item.relative}\0{item.size}\0{item.sha256}\n" for item in files]
    return hashlib.sha256("".join(sorted(values)).encode("utf-8")).hexdigest()


def require_inside(path: Path, parent: Path) -> Path:
    resolved = path.resolve()
    if not resolved.is_relative_to(parent.resolve()):
        raise AssetError(f"Path escapes allowed directory: {path}")
    return resolved


def checked_file(path: Path, descriptor: dict, relative: str, group: str) -> MediaFile:
    expected_size, expected_hash = descriptor.get("bytes"), descriptor.get("sha256")
    if type(expected_size) is not int or expected_size <= 0:
        raise AssetError(f"Missing or invalid file size: {relative}")
    if not isinstance(expected_hash, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_hash):
        raise AssetError(f"Missing or invalid SHA-256: {relative}")
    if not path.is_file() or path.is_symlink():
        raise AssetError(f"Missing file or unsupported symlink: {path}")
    if path.stat().st_size != expected_size or digest(path) != expected_hash:
        raise AssetError(f"Size or SHA-256 mismatch: {relative}")
    return MediaFile(path, relative, expected_size, expected_hash, group)


def load_release(source: Path) -> tuple[dict, list[MediaFile]]:
    source = source.resolve()
    main_path = source / "app-manifest.json"
    if not main_path.is_file() or main_path.is_symlink():
        raise AssetError(f"Missing app manifest: {main_path}")
    main_bytes = main_path.read_bytes()
    manifest = json.loads(main_bytes)
    version = manifest.get("version")
    if not isinstance(version, str) or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise AssetError("Release version must be a numeric semantic version")
    if source.name != f"v{version}-app":
        raise AssetError("Source directory must be named v<manifest.version>-app")
    files = [MediaFile(main_path, f"{source.name}/app-manifest.json", len(main_bytes),
                       hashlib.sha256(main_bytes).hexdigest(), "manifests")]
    inputs = list(files)
    for package_id in ("builtin", "realistic-dark", "common"):
        package = manifest["packages"][package_id]
        descriptor = package["manifest"]
        subpath = descriptor["path"]
        if subpath != f"packages/{package_id}.json":
            raise AssetError(f"Unexpected submanifest path: {subpath}")
        subfile = checked_file(source / subpath, descriptor,
                               f"{source.name}/{subpath}", "manifests")
        inputs.append(subfile)
        if package_id in BUNDLED_PACKAGES:
            files.append(subfile)
        entries = json.loads(subfile.source.read_bytes())["files"]
        if len(entries) != package["fileCount"]:
            raise AssetError(f"File count mismatch: {package_id}")
        if sum(item["bytes"] for item in entries) != package["totalBytes"]:
            raise AssetError(f"Total bytes mismatch: {package_id}")
        if package_id == "builtin" and len(entries) != BUILTIN_VIDEO_COUNT:
            raise AssetError(f"Expected {BUILTIN_VIDEO_COUNT} builtin videos")
        seen_paths: set[str] = set()
        for entry in entries:
            relative = entry["path"]
            if not isinstance(relative, str) or "\\" in relative:
                raise AssetError(f"Invalid media path: {relative}")
            parts = PurePosixPath(relative).parts
            if package_id == "common":
                valid = (len(parts) == 3 and parts[0] == "common-lossy"
                         and parts[1] in ("covers", "thumbs")
                         and PurePosixPath(relative).suffix == ".webp")
                group = parts[1] if valid else "invalid"
            else:
                valid = (len(parts) == 5 and parts[:4] == ("..", f"v{version}", "realistic", "dark")
                         and PurePosixPath(relative).suffix == ".mp4")
                group = "videos"
            if not valid or relative in seen_paths:
                raise AssetError(f"Unexpected or duplicate media path: {relative}")
            seen_paths.add(relative)
            # realistic-dark indexes downloadable files: verify only its
            # submanifest here. Those videos must never become builtin assets.
            if package_id == "realistic-dark":
                continue
            original = require_inside(source / relative, source.parent)
            destination = original.relative_to(source.parent).as_posix()
            item = checked_file(original, entry, destination, group)
            inputs.append(item)
            files.append(item)
    if len({item.relative for item in files}) != len(files):
        raise AssetError("Duplicate destination path")
    action_ids = {action["id"] for action in manifest["actions"]}
    for group in ("covers", "thumbs"):
        ids = {Path(item.relative).stem for item in files if item.group == group}
        if ids != action_ids:
            raise AssetError(f"{group} must cover every manifest action exactly once")
    video_ids = {Path(item.relative).stem for item in files if item.group == "videos"}
    if video_ids != set(manifest["packages"]["builtin"]["actionIds"]):
        raise AssetError("Builtin videos do not match builtin action IDs")
    # Keep every input, including unbundled common.json, for read-only auditing.
    manifest["_buildInputs"] = inputs
    return manifest, sorted(files, key=lambda item: item.relative)


def old_media(app_root: Path) -> list[Path]:
    packs = app_root / "assets" / "packs"
    paths = set(packs.glob("*/demo*.mp4")) | set(packs.glob("*/cover*.jpg"))
    for path in paths:
        require_inside(path, packs)
        if path.is_symlink() or not path.is_file():
            raise AssetError(f"Unsupported legacy media path: {path}")
    return sorted(paths)


def protected_inventory(app_root: Path) -> str:
    root = app_root / "assets" / "packs"
    legacy = set(old_media(app_root))
    files = [MediaFile(p, p.relative_to(root).as_posix(), p.stat().st_size,
                       digest(p), "preserved")
             for p in root.rglob("*") if p.is_file() and p not in legacy]
    return inventory_hash(files)


def pubspec_assets(pubspec: str, files: list[MediaFile]) -> str:
    directories = sorted({"assets/training_media/" + str(PurePosixPath(item.relative).parent) + "/"
                          for item in files})
    block = BEGIN + "\n" + "\n".join(f"    - {directory}" for directory in directories) + "\n" + END
    pubspec = re.sub(r"^    - assets/cutouts/[^\n]*\n", "", pubspec, flags=re.MULTILINE)
    if BEGIN in pubspec:
        start = pubspec.index(BEGIN)
        end = pubspec.index(END, start) + len(END)
        return pubspec[:start] + block + pubspec[end:]
    marker = "  assets:\n"
    if pubspec.count(marker) != 1:
        raise AssetError("Expected exactly one flutter.assets section")
    return pubspec.replace(marker, marker + block + "\n", 1)


def apk_baseline(path: Path) -> dict:
    with zipfile.ZipFile(path) as apk:
        infos = apk.infolist()
        media = [item for item in infos if item.filename.startswith("assets/flutter_assets/assets/packs/")
                 and (item.filename.endswith(".mp4") or item.filename.endswith(".jpg"))]
        cutouts = [item for item in infos if item.filename.startswith("assets/flutter_assets/assets/cutouts/")]
        def totals(entries: list) -> dict:
            return {"files": len(entries), "bytes": sum(item.file_size for item in entries),
                    "compressedBytes": sum(item.compress_size for item in entries)}
        return {"file": path.name, "bytes": path.stat().st_size, "sha256": digest(path),
                "legacyPackMedia": totals(media), "cutouts": totals(cutouts)}


def verify_output(app_root: Path, files: list[MediaFile]) -> None:
    destination = app_root / "assets" / "training_media"
    actual = {item.relative_to(destination).as_posix()
              for item in destination.rglob("*") if item.is_file()}
    expected = {item.relative for item in files}
    if actual != expected:
        raise AssetError(f"Builtin asset set differs: missing={sorted(expected - actual)}, "
                         f"extra={sorted(actual - expected)}")
    for item in files:
        checked_file(destination / item.relative,
                     {"bytes": item.size, "sha256": item.sha256}, item.relative, item.group)
    if old_media(app_root):
        raise AssetError("Legacy demo videos or covers still exist in assets/packs")
    pubspec = (app_root / "pubspec.yaml").read_text("utf-8")
    if pubspec_assets(pubspec, files) != pubspec:
        raise AssetError("pubspec assets do not match the builtin bundle")


def _offline_themes(source: Path, app_root: Path, manifest: dict,
                    files: list[MediaFile], staging: Path) -> list[MediaFile]:
    """Add only existing release files; never infer that an action has a video."""
    from PIL import Image

    version = manifest['version']
    index = json.loads((app_root / 'assets/packs/index.json').read_bytes())
    ids = sorted(entry['id'] for entry in index['packs']
                 if entry.get('kind') == 'exercise')
    available_ids = {entry['id'] for entry in manifest['actions']}
    if set(ids) - available_ids:
        raise AssetError('App exercise metadata is absent from the release')
    inputs = manifest['_buildInputs']
    outputs = {item.relative: item for item in files}
    variants = {}
    for theme in ('dark', 'light'):
        descriptors = {}
        frames = {}
        package_ids = (['builtin'] if theme == 'dark' else []) + [
            f'realistic-{theme}', f'keyframes-realistic-{theme}']
        for package_id in package_ids:
            package = manifest['packages'][package_id]
            ref = package['manifest']
            if ref['path'] != f'packages/{package_id}.json':
                raise AssetError('Unexpected submanifest path')
            subfile = checked_file(source / ref['path'], ref,
                                   f'{source.name}/{ref["path"]}', 'manifests')
            inputs.append(subfile)
            if package_id == f'realistic-{theme}':
                outputs[subfile.relative] = subfile
            entries = json.loads(subfile.source.read_bytes())['files']
            if len(entries) != package['fileCount'] or sum(f['bytes'] for f in entries) != package['totalBytes']:
                raise AssetError(f'Package size/count mismatch: {package_id}')
            for entry in entries:
                relative = entry['path']
                parts = PurePosixPath(relative).parts
                if '\\' in relative or parts[:4] != ('..', f'v{version}', 'realistic', theme):
                    raise AssetError(f'Unexpected media path: {relative}')
                if package['kind'] == 'keyframes':
                    if len(parts) != 6 or parts[4] != 'keyframes' or not parts[5].endswith('.webp'):
                        raise AssetError(f'Unexpected keyframe path: {relative}')
                    aid = re.sub(r'_[123]\.webp$', '', parts[5])
                    if aid in ids and parts[5] == f'{aid}_2.webp':
                        if aid in frames:
                            raise AssetError(f'Duplicate poster frame: {aid}/{theme}')
                        frames[aid] = entry
                else:
                    if len(parts) != 5 or not parts[4].endswith('.mp4'):
                        raise AssetError(f'Unexpected video path: {relative}')
                    aid = PurePosixPath(relative).stem
                    if aid in ids:
                        if aid in descriptors:
                            raise AssetError(f'Duplicate video: {aid}/{theme}')
                        descriptors[aid] = entry
        variants[theme] = (descriptors, frames)
    asset_index = {'format': 'smartfit-offline-media@1', 'version': version,
                   'sourceAppManifestSha256': digest(source / 'app-manifest.json'),
                   'actions': {}}
    for aid in ids:
        asset_index['actions'][aid] = {}
        for theme, (videos, frames) in variants.items():
            if aid not in frames:
                raise AssetError(f'Missing {theme} exported still for {aid}; request a Pose-Hub export')
            frame = frames[aid]
            original = require_inside(source / frame['path'], source.parent)
            checked = checked_file(original, frame, original.relative_to(source.parent).as_posix(), 'source-stills')
            inputs.append(checked)
            item = {'video': None}
            if aid in videos:
                video = videos[aid]
                original_video = require_inside(source / video['path'], source.parent)
                copied = checked_file(original_video, video, original_video.relative_to(source.parent).as_posix(), 'videos')
                inputs.append(copied)
                outputs[copied.relative] = copied
                item['video'] = {'asset': 'assets/training_media/' + copied.relative,
                                 'bytes': copied.size, 'sha256': copied.sha256}
            for role, directory, size, quality in [('poster', 'covers', 720, 82), ('thumbnail', 'thumbs', 240, 80)]:
                relative = f'{source.name}/theme-lossy/{theme}/{directory}/{aid}.webp'
                target = staging / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                with Image.open(original) as image:
                    image = image.convert('RGB')
                    image.thumbnail((size, size), Image.Resampling.LANCZOS)
                    image.save(target, format='WEBP', quality=quality, method=6)
                generated = MediaFile(target, relative, target.stat().st_size, digest(target), 'theme-' + directory)
                outputs[relative] = generated
                item[role] = {'asset': 'assets/training_media/' + relative,
                              'bytes': generated.size, 'sha256': generated.sha256,
                              'sourceSha256': checked.sha256}
            asset_index['actions'][aid][theme] = item
    relative = f'{source.name}/assets-index.json'
    target = staging / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(asset_index, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    outputs[relative] = MediaFile(target, relative, target.stat().st_size, digest(target), 'manifests')
    manifest['_offlineActions'] = ids
    return sorted(outputs.values(), key=lambda item: item.relative)


def build(source: Path, app_root: Path, *, apply: bool = False,
          verify_only: bool = False, baseline_apk: Path | None = None,
          offline_themes: bool = False) -> dict:
    # Temporary generated images never enter the read-only Pose-Hub release.
    with tempfile.TemporaryDirectory(prefix='smartfit-theme-stills-') as name:
        return _build(source, app_root, apply=apply, verify_only=verify_only,
                      baseline_apk=baseline_apk,
                      offline_staging=Path(name) if offline_themes else None)


def _build(source: Path, app_root: Path, *, apply: bool = False,
           verify_only: bool = False, baseline_apk: Path | None = None,
           offline_staging: Path | None = None) -> dict:
    source, app_root = source.resolve(), app_root.resolve()
    destination = app_root / "assets" / "training_media"
    if source.is_relative_to(app_root) or app_root.is_relative_to(source.parent):
        raise AssetError("Source release and application workspace must not overlap")
    require_inside(destination, app_root)
    if (app_root / "assets").is_symlink() or destination.is_symlink():
        raise AssetError("Application asset roots must not be symlinks")
    manifest, files = load_release(source)
    if offline_staging is not None:
        files = _offline_themes(source, app_root, manifest, files, offline_staging)
    inputs = manifest.pop("_buildInputs")
    original_sources = inventory_hash(inputs)
    original_metadata = protected_inventory(app_root)
    legacy = old_media(app_root)
    pubspec_path = app_root / "pubspec.yaml"
    updated_pubspec = pubspec_assets(pubspec_path.read_text("utf-8"), files)
    # Refuse to erase any unrecognized existing asset, even during --apply.
    for path in destination.rglob("*"):
        require_inside(path, destination)
        if path.is_symlink():
            raise AssetError(f"Unsupported destination symlink: {path}")
        if path.is_file() and path.relative_to(destination).as_posix() not in {f.relative for f in files}:
            raise AssetError(f"Unexpected existing asset (preserved): {path}")
    if apply:
        # Validate every source before changing the application; stage and verify
        # copies before atomically replacing known outputs.
        with tempfile.TemporaryDirectory(prefix="builtin-media-", dir=app_root / "assets") as stage_name:
            stage = Path(stage_name)
            for item in files:
                target = stage / item.relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(item.source, target)
                checked_file(target, {"bytes": item.size, "sha256": item.sha256}, item.relative, item.group)
            for item in files:
                target = destination / item.relative
                require_inside(target, destination)
                target.parent.mkdir(parents=True, exist_ok=True)
                (stage / item.relative).replace(target)
        for path in legacy:
            # Removal is limited to the explicit, verified App worktree above.
            require_inside(path, app_root / "assets" / "packs")
            path.unlink()
        pubspec_path.write_text(updated_pubspec, encoding="utf-8", newline="\n")
    if apply or verify_only:
        verify_output(app_root, files)
    # Rehash input bytes after application to prove neither the release nor
    # training metadata, voices, chimes or license files were modified.
    rechecked = [checked_file(item.source, {"bytes": item.size, "sha256": item.sha256},
                             item.relative, item.group) for item in inputs]
    if inventory_hash(rechecked) != original_sources:
        raise AssetError("Release inputs changed during build")
    if protected_inventory(app_root) != original_metadata:
        raise AssetError("Protected pack files changed during build")
    counts = Counter(item.group for item in files)
    report = {
        "releaseVersion": manifest["version"],
        "mainCommit": manifest.get("mainCommit"),
        "mainManifestSha256": next(item.sha256 for item in files
                                   if item.relative.endswith("/app-manifest.json")),
        "bundledSubmanifests": [f"packages/{name}.json" for name in BUNDLED_PACKAGES] +
                              (["packages/realistic-light.json"] if offline_staging is not None else []),
        "offlineThemes": ["dark", "light"] if offline_staging is not None else [],
        "offlineActionCount": len(manifest.get('_offlineActions', [])),
        "groups": {group: {"files": counts[group],
                           "bytes": sum(item.size for item in files if item.group == group)}
                   for group in sorted(counts)},
        "bundle": {"files": len(files), "bytes": sum(item.size for item in files)},
        "bundleInventorySha256": inventory_hash(files),
        "sourceInputs": {"files": len(inputs), "inventorySha256": original_sources,
                         "unchangedAfterBuild": True},
        "protectedPackFilesInventorySha256": original_metadata,
        "legacyPackMediaRemaining": len(old_media(app_root)),
        "cutoutsBundled": False,
        "validatedOutput": apply or verify_only,
    }
    if not apply and not verify_only:
        report["previewLegacyRemoval"] = {"files": len(legacy), "bytes": sum(p.stat().st_size for p in legacy)}
    if baseline_apk is not None:
        report["baselineApk"] = apk_baseline(baseline_apk)
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--app-root", default=APP_ROOT, type=Path)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--verify-only", action="store_true")
    parser.add_argument("--baseline-apk", type=Path)
    parser.add_argument("--legacy-small-bundle", action="store_true",
                        help="Retain the original 32-video dark-only bundle")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    report = build(args.source, args.app_root, apply=args.apply,
                   verify_only=args.verify_only, baseline_apk=args.baseline_apk,
                   offline_themes=not args.legacy_small_bundle)
    encoded = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if args.report:
        args.report.write_text(encoded, encoding="utf-8", newline="\n")
    print(encoded, end="")


if __name__ == "__main__":
    main()
