#!/usr/bin/env python3
"""Seal drill packs after editing them (docs/drill-pack-spec.md).

For every assets/packs/<id>/pack.json:
  * writes `files` — every file the pack carries, with byte size and sha256
    (validate_packs.py and other apps check a copied pack against it);
  * refuses to seal a pack whose voice line has no decoded length yet
    (run tools/voice/build_voice.py first) or that references a missing file;
then writes assets/packs/index.json (what an app loads first) and, with
--pubspec, rewrites the generated asset block of pubspec.yaml (Flutter does
not include sub-folders of an asset folder, so each pack folder is listed).

    python3 tools/packs/build_packs.py [--root assets/packs] [--pubspec pubspec.yaml]

Standard library only; copy tools/packs/ into another repo to use it there.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import packlib as P  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BEGIN = '    # BEGIN drill packs (generated by tools/packs/build_packs.py — do not edit)'
END = '    # END drill packs'


def seal(d: Path, errors: list) -> dict:
    pack = P.read_json(d / 'pack.json')
    voice = pack.get('voice') or {}
    for line in voice.get('lines', []):
        for lang in voice.get('languages', []):
            if lang in line.get('text', {}) and not (line.get('ms') or {}).get(lang):
                errors.append(f"{d.name}: line {line['id']} [{lang}] has no decoded length "
                              '(run tools/voice/build_voice.py)')
    files = {}
    for rel in sorted(set(P.listed_files(pack))):
        f = d / rel
        if not f.is_file():
            errors.append(f'{d.name}: missing {rel}')
            continue
        files[rel] = {'bytes': f.stat().st_size, 'sha256': P.sha256(f)}
    pack['files'] = files
    P.write_json(d / 'pack.json', pack)
    return pack


def speech_bundle_directories(root: Path, repo: Path):
    """An optional encoded voice bundle replaces original speech in the APK.

    Original pack files/checksums stay intact for reuse and later re-encoding.
    The pack index pins the selected manifest; never infer a profile merely
    from a directory happening to exist.
    """
    index_path = root / 'index.json'
    selected = P.read_json(index_path).get('voiceBundle') if index_path.exists() else None
    if selected is None:
        return None
    manifest_path = (repo / selected['asset']).resolve()
    if not manifest_path.is_relative_to((repo / 'assets').resolve()):
        raise ValueError('voiceBundle must be an application asset')
    if (manifest_path.stat().st_size != selected['bytes']
            or P.sha256(manifest_path) != selected['sha256']):
        raise ValueError('Selected voiceBundle manifest size/sha256 mismatch')
    manifest = P.read_json(manifest_path)
    if manifest.get('schema_version') != 1 or not manifest.get('clips'):
        raise ValueError('Unsupported/empty voiceBundle manifest')
    paths = [manifest_path]
    for clip in manifest['clips']:
        original = (root / clip['pack'] / 'voice' / clip['lang'] / f'{clip["line"]}.m4a').resolve()
        if (not original.is_relative_to(root.resolve())
                or clip['source']['asset'] != original.relative_to(repo).as_posix()
                or P.sha256(original) != clip['source']['sha256']):
            raise ValueError('voiceBundle source changed; convert the updated originals before packaging')
        path = (repo / clip['asset']).resolve()
        if not path.is_relative_to(manifest_path.parent) or path == manifest_path:
            raise ValueError('voiceBundle speech must be inside its versioned root')
        if path.stat().st_size != clip['bytes'] or P.sha256(path) != clip['sha256']:
            raise ValueError(f'voiceBundle clip size/sha256 mismatch: {clip["asset"]}')
        paths.append(path)
    return sorted({p.parent.relative_to(repo).as_posix() for p in paths})


def pubspec_block(root: Path, repo: Path, dirs) -> list[str]:
    rel = root.relative_to(repo).as_posix()
    speech_dirs = speech_bundle_directories(root, repo)
    out = [BEGIN, f'    - {rel}/']
    for d in dirs:
        pack = P.read_json(d / 'pack.json')
        out.append(f'    - {rel}/{d.name}/')
        if pack.get('chimes'):
            out.append(f'    - {rel}/{d.name}/chime/')
        if speech_dirs is None:
            for lang in (pack.get('voice') or {}).get('languages', []):
                out.append(f'    - {rel}/{d.name}/voice/{lang}/')
    for directory in speech_dirs or []:
        out.append(f'    - {directory}/')
    out.append(END)
    return out


def write_pubspec(path: Path, block: list[str]) -> None:
    lines = path.read_text(encoding='utf-8').split('\n')
    if BEGIN in lines:
        a, b = lines.index(BEGIN), lines.index(END)
        lines[a:b + 1] = block
    else:
        i = next(k for k, l in enumerate(lines) if l.strip() == 'assets:')
        lines[i + 1:i + 1] = block
    path.write_text('\n'.join(lines), encoding='utf-8')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=str(P.packs_root(ROOT)))
    ap.add_argument('--pubspec', help='rewrite the generated asset block of this pubspec.yaml')
    a = ap.parse_args()
    root = Path(a.root).resolve()
    existing_index = P.read_json(root / 'index.json') if (root / 'index.json').exists() else {}
    dirs = P.pack_dirs(root)
    errors, entries, total = [], [], 0
    for d in dirs:
        pack = seal(d, errors)
        size = sum(f['bytes'] for f in pack['files'].values())
        total += size
        entries.append({
            'id': pack['id'], 'kind': pack['kind'], 'version': pack['version'],
            'name': pack['name'], 'bytes': size,
            'sha256': P.sha256(d / 'pack.json'),
        })
    index = {
        'format': P.INDEX_FORMAT,
        'formatVersion': P.FORMAT_VERSION,
        'common': P.COMMON_ID,
        'packs': entries,
    }
    if 'voiceBundle' in existing_index:
        index['voiceBundle'] = existing_index['voiceBundle']
    P.write_json(root / 'index.json', index)
    if a.pubspec:
        repo = Path(a.pubspec).resolve().parent
        write_pubspec(Path(a.pubspec), pubspec_block(root, repo, dirs))
    for e in errors:
        print('ERROR', e, file=sys.stderr)
    n_ex = sum(1 for e in entries if e['kind'] == 'exercise')
    print(f'{n_ex} exercise packs + {len(entries) - n_ex} common, {total / 1024 / 1024:.1f} MB '
          f'-> {root / "index.json"}')
    sys.exit(1 if errors else 0)


if __name__ == '__main__':
    main()
